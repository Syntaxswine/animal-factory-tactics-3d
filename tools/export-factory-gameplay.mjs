import fs from 'node:fs';
import {createHash} from 'node:crypto';
import * as T from '../dist/tactics/vendor/three.module.js';
import {SCENERY_PROPS,SCENERY_FLOOR} from '../dist/tactics/scenery-catalog.js';

// Authoritative, deterministic reduced-mesh bake. No browser or renderer.
const root=new URL('../',import.meta.url),files=['tools/export-factory-gameplay.mjs','dist/tactics/scenery-catalog.js'],records={},sources={};
const sha=s=>createHash('sha256').update(s).digest('hex'),pack=a=>Buffer.from(new Float32Array(a).buffer).toString('base64');
for(const form of ['lathe','mill','press']){
 const file=`dist/tactics/machine-${form}-10k-data.json`,source=fs.readFileSync(new URL(file,root)),model=JSON.parse(source),rule=SCENERY_PROPS['machine-'+form];
 // Git checkouts may use CRLF on Windows. Hash canonical text so the same
 // committed meshes reproduce on Windows, Linux and macOS.
 sources[file]=sha(source.toString('utf8').replace(/\r\n/g,'\n'));files.push(file);
 const triangles=[];
 for(const p of model.parts)for(let i=0;i<p.index.length;i+=3){const t=[];for(let j=0;j<3;j++){const k=p.index[i+j]*3;t.push(p.position[k]+rule.origin[0],p.position[k+2]+rule.origin[1],p.position[k+1]);}triangles.push(t);}
 const nodes=[],packed=[];
 function tree(items){
  const b=[Infinity,Infinity,Infinity,-Infinity,-Infinity,-Infinity];for(const t of items)for(let i=0;i<9;i++){const k=i%3;b[k]=Math.min(b[k],t[i]);b[k+3]=Math.max(b[k+3],t[i]);}
  // Outward rounding prevents Float32 bounds from dropping a surface.
  for(let k=0;k<3;k++){b[k]=Math.floor(b[k]*1e5)/1e5;b[k+3]=Math.ceil(b[k+3]*1e5)/1e5;}
  const id=nodes.length;nodes.push(null);
  if(items.length<=12){nodes[id]=[...b,-packed.length/9-1,items.length];for(const t of items)packed.push(...t);}
  else{const spans=[0,1,2].map(k=>b[k+3]-b[k]),axis=spans.indexOf(Math.max(...spans));items.sort((a,c)=>(a[axis]+a[axis+3]+a[axis+6])-(c[axis]+c[axis+3]+c[axis+6]));const half=items.length>>1;nodes[id]=[...b,tree(items.slice(0,half)),tree(items.slice(half))];}return id;
 }
 tree(triangles);
 const physical=triangles.map(t=>new T.Triangle(...[0,3,6].map(i=>new T.Vector3(...t.slice(i,i+3))))),box=new T.Box3();
 const clear=(x,y,u=x,v=y,level=0)=>{box.min.set(Math.min(x,u)-.28,Math.min(y,v)-.28,level*SCENERY_FLOOR+.08);box.max.set(Math.max(x,u)+.28,Math.max(y,v)+.28,level*SCENERY_FLOOR+1.75);return !physical.some(t=>box.intersectsTriangle(t));};
 const clearance=[];
 for(let level=0;level*SCENERY_FLOOR<nodes[0][5];level++){
  const rows=Array.from({length:rule.h},(_,y)=>Array.from({length:rule.w},(_,x)=>clear(x,y,x,y,level)?'.':'#').join('')),links=[];
  // Include the surrounding ring: a diagonal can clip a base even when neither
  // endpoint lies in the reservation. Include entrances into that ring too.
  for(let y=-2;y<=rule.h+1;y++)for(let x=-2;x<=rule.w+1;x++)for(const [dx,dy]of [[1,0],[0,1],[1,1],[-1,1]]){const u=x+dx,v=y+dy,inside=(a,b)=>a>=-1&&a<=rule.w&&b>=-1&&b<=rule.h;if((inside(x,y)||inside(u,v))&&clear(x,y,u,v,level))links.push([x,y,u,v]);}
  clearance.push({rows,links});
 }
 records[form]={bounds:nodes[0].slice(0,6),triangleCount:packed.length/9,nodes:pack(nodes.flat()),triangles:pack(packed),clearance};
 console.log(`${form}: ${packed.length/9} triangles, clearance ${clearance.map(c=>c.rows.join('/')).join(' | ')}`);
}
const hash=createHash('sha256');for(const file of files)hash.update(fs.readFileSync(new URL(file,root),'utf8').replace(/\r\n/g,'\n'));
const text='// Generated by tools/export-factory-gameplay.mjs. Do not edit.\nexport const FACTORY_GEOMETRY_VERSION=1;\nexport const FACTORY_GEOMETRY_HASH='+JSON.stringify(hash.digest('hex'))+';\nexport const FACTORY_GEOMETRY_SOURCES='+JSON.stringify(sources)+';\nexport const FACTORY_PACKED='+JSON.stringify(records)+';\n';
const dest=new URL('dist/tactics/factory-gameplay-data.js',root);
if(process.argv.includes('--check')){if(fs.readFileSync(dest,'utf8').replace(/\r\n/g,'\n')!==text)throw Error('Factory geometry is stale: run node tools/export-factory-gameplay.mjs');}else fs.writeFileSync(dest,text);
console.log(`Factory geometry ${process.argv.includes('--check')?'verified':'baked'}: ${Math.round(text.length/1024)} KiB.`);
