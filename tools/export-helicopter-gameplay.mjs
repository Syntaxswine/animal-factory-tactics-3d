import fs from 'node:fs';
import {createHash} from 'node:crypto';
import * as T from '../dist/tactics/vendor/three.module.js';
import {createUtilityHelicopter} from '../dist/tactics/utility-helicopter.js';
import {HELICOPTER_FOOTPRINT as F} from '../dist/tactics/scenery-catalog.js';

// Bake the real model once, including a standing-body sweep for each grid link.
// Overhead parts still stop bullets. Cosmetic ground scars never do.
const texture=new T.Texture(),data={},round=n=>Math.round(n*1e5)/1e5;
try{
 for(const state of ['intact','survivable','crashed']){
  const model=createUtilityHelicopter(texture,{state});model.root.updateMatrixWorld(true);
  try{
   const triangles=[],physical=[];
   model.root.traverse(mesh=>{
    if(!mesh.isMesh||mesh.userData.role==='ground')return;
    const pos=mesh.geometry.attributes.position,index=mesh.geometry.index,count=index?.count??pos.count;
    for(let i=0;i<count;i+=3){
     const points=[];for(let j=0;j<3;j++){const v=new T.Vector3().fromBufferAttribute(pos,index?index.getX(i+j):i+j).applyMatrix4(mesh.matrixWorld);points.push(new T.Vector3(round(v.x+F.origin[0]),round(v.z+F.origin[1]),round(v.y)));}
     physical.push(new T.Triangle(...points));triangles.push(points.flatMap(v=>v.toArray()));
    }
   });
   const nodes=[],packed=[];
   function tree(items){
    const b=[Infinity,Infinity,Infinity,-Infinity,-Infinity,-Infinity];for(const t of items)for(let i=0;i<9;i++){const k=i%3;b[k]=Math.min(b[k],t[i]);b[k+3]=Math.max(b[k+3],t[i]);}
    const id=nodes.length;nodes.push(null);
    if(items.length<=12){nodes[id]=[...b,-packed.length/9-1,items.length];for(const t of items)packed.push(...t);}
    else{const spans=[0,1,2].map(k=>b[k+3]-b[k]),axis=spans.indexOf(Math.max(...spans));items.sort((a,c)=>(a[axis]+a[axis+3]+a[axis+6])-(c[axis]+c[axis+3]+c[axis+6]));const half=items.length>>1;nodes[id]=[...b,tree(items.slice(0,half)),tree(items.slice(half))];}return id;
   }
   tree(triangles);
   const body=new T.Box3(),clear=(x,y)=>{body.min.set(x-.28,y-.28,.08);body.max.set(x+.28,y+.28,1.75);return !physical.some(t=>body.intersectsTriangle(t));};
   const rows=Array.from({length:F.h},(_,y)=>Array.from({length:F.w},(_,x)=>clear(x,y)?'.':'#').join('')),links=[];
   // Include one outside cell to test the actual entrance, not just endpoints.
   for(let y=-1;y<=F.h;y++)for(let x=-1;x<=F.w;x++)for(const [dx,dy]of [[1,0],[0,1],[1,1],[-1,1]]){
    const u=x+dx,v=y+dy,inside=(a,b)=>a>=0&&a<F.w&&b>=0&&b<F.h;if(!inside(x,y)&&!inside(u,v))continue;
    let safe=true;for(let i=0;i<=20&&safe;i++)safe=clear(x+dx*i/20,y+dy*i/20);if(safe)links.push([x,y,u,v]);
   }
   data[state]={nodes,triangles:packed,clearance:{rows,links}};
  }finally{model.dispose();}
 }
 const hash=createHash('sha256');for(const file of ['dist/tactics/utility-helicopter.js','dist/tactics/scenery-catalog.js','tools/export-helicopter-gameplay.mjs'])hash.update(fs.readFileSync(new URL('../'+file,import.meta.url),'utf8').replace(/\r\n/g,'\n'));
 const text='// Generated by tools/export-helicopter-gameplay.mjs. Do not edit.\nexport const HELICOPTER_GEOMETRY_HASH='+JSON.stringify(hash.digest('hex'))+';\nexport const HELICOPTER_DATA='+JSON.stringify(data)+';\n',dest=new URL('../dist/tactics/helicopter-gameplay-data.js',import.meta.url);
 if(process.argv.includes('--check')){if(fs.readFileSync(dest,'utf8').replace(/\r\n/g,'\n')!==text)throw Error('Helicopter geometry is stale');}else fs.writeFileSync(dest,text);
 console.log(`Helicopter geometry ${process.argv.includes('--check')?'verified':'baked'}: ${Math.round(text.length/1024)} KiB.`);
}finally{texture.dispose();}
