import fs from 'node:fs';
import {createHash} from 'node:crypto';
import * as T from '../dist/tactics/vendor/three.module.js';
import {STRATEGIC_SITES,createStrategicSiteLibrary} from '../dist/tactics/strategic-sites.js';

// Bake once, never prepare geometry or passage sweeps during a first encounter.
// The renderer and these triangle colliders are generated from the same models.
const url=p=>new URL('../'+p,import.meta.url),manifest=JSON.parse(fs.readFileSync(url('dist/assets/environment/strategic-sites/manifest.json')));
const texture=new T.Texture(),library=createStrategicSiteLibrary(texture),data={};
const round=n=>Math.round(n*100000)/100000;
try {
 for(const site of STRATEGIC_SITES)for(const state of ['intact','destroyed']){
  const {root}=library.build(site.id,{state});root.updateMatrixWorld(true);
  const triangles=[],samples=new Map();
  root.traverse(mesh=>{
   if(!mesh.isMesh)return;
   const position=mesh.geometry.attributes.position,index=mesh.geometry.index,count=index?.count??position.count;
   for(let i=0;i<count;i+=3){
    const tri=[];
    for(let j=0;j<3;j++){const v=new T.Vector3().fromBufferAttribute(position,index?index.getX(i+j):i+j).applyMatrix4(mesh.matrixWorld);tri.push(round(v.x+3.5),round(v.z+3.5),round(v.y));}
    triangles.push(tri);
    // Physical equipment surfaces, excluding the harmless concrete hardstanding.
    const p=[0,1,2].map(k=>(tri[k]+tri[k+3]+tri[k+6])/3);
    if(p[2]>.32){const key=p.map(n=>Math.floor(n*2)).join(',');if(!samples.has(key))samples.set(key,p.map(round));}
   }
  });
  const nodes=[],packed=[];
  function tree(items){
   const bounds=[Infinity,Infinity,Infinity,-Infinity,-Infinity,-Infinity];
   for(const tri of items)for(let i=0;i<9;i++) {const k=i%3;bounds[k]=Math.min(bounds[k],tri[i]);bounds[k+3]=Math.max(bounds[k+3],tri[i]);}
   const id=nodes.length;nodes.push(null);
   if(items.length<=12){nodes[id]=[...bounds,-packed.length/9-1,items.length];for(const tri of items)packed.push(...tri);}
   else {const sizes=[0,1,2].map(k=>bounds[k+3]-bounds[k]),axis=sizes.indexOf(Math.max(...sizes));items.sort((a,b)=>(a[axis]+a[axis+3]+a[axis+6])-(b[axis]+b[axis+3]+b[axis+6]));const half=Math.floor(items.length/2);nodes[id]=[...bounds,tree(items.slice(0,half)),tree(items.slice(half))];}
   return id;
  }
  tree(triangles);
  const asset=manifest.assets.find(a=>a.siteId===site.id&&a.state===state);
  data[site.id+'-'+state]={height:asset.height,clearance:asset.clearance.wide,nodes,triangles:packed,samples:[...samples.values()]};
 }
 const sourceHash=createHash('sha256');
 for(const p of ['dist/tactics/strategic-sites.js','dist/tactics/strategic-site-clearance.js','dist/assets/environment/strategic-sites/manifest.json'])sourceHash.update(fs.readFileSync(url(p),'utf8').replace(/\r\n/g,'\n'));
 const text='// Generated by tools/export-strategic-site-gameplay.mjs. Do not edit.\nexport const SITE_GEOMETRY_HASH='+JSON.stringify(sourceHash.digest('hex'))+';\nexport const SITE_DATA='+JSON.stringify(data)+';\n';
 const dest=url('dist/tactics/strategic-site-data.js');
 if(process.argv.includes('--check')){if(fs.readFileSync(dest,'utf8').replace(/\r\n/g,'\n')!==text)throw Error('Strategic gameplay geometry is stale');}
 else fs.writeFileSync(dest,text);
 console.log('Strategic gameplay geometry '+(process.argv.includes('--check')?'verified':'baked')+': '+Math.round(text.length/1024)+' KiB, six forms.');
}finally{library.dispose();texture.dispose();}
